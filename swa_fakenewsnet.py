import pandas as pd
import numpy as np
import re
import matplotlib.pyplot as plt
import seaborn as sns
from scipy.sparse import hstack, csr_matrix

from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.svm import LinearSVC
from sklearn.naive_bayes import MultinomialNB
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score,
    confusion_matrix, classification_report, roc_auc_score, roc_curve
)

RANDOM_STATE = 42
NUMERIC_COLS = ['title_length', 'tweet_count', 'exclaim_count', 'question_count', 'has_url']


# ---------------------------------------------------------------------------
# 1. LOAD & MERGE DATA
# ---------------------------------------------------------------------------
def load_data():
    pf_fake = pd.read_csv('politifact_fake.csv')
    pf_real = pd.read_csv('politifact_real.csv')
    gc_fake = pd.read_csv('gossipcop_fake.csv')
    gc_real = pd.read_csv('gossipcop_real.csv')

    pf_fake['label'], pf_real['label'] = 1, 0        # 1 = fake, 0 = real
    gc_fake['label'], gc_real['label'] = 1, 0
    pf_fake['source'], pf_real['source'] = 'politifact', 'politifact'
    gc_fake['source'], gc_real['source'] = 'gossipcop', 'gossipcop'

    df = pd.concat([pf_fake, pf_real, gc_fake, gc_real], ignore_index=True)
    print(f"Loaded {len(df)} rows total.")
    print(df['source'].value_counts())
    print(df['label'].value_counts().rename({0: 'real', 1: 'fake'}))
    return df


# ---------------------------------------------------------------------------
# 2. CLEANING & FEATURE ENGINEERING
# ---------------------------------------------------------------------------
def clean_text(text):
    """Lowercase, strip URLs/punctuation/extra whitespace."""
    if pd.isna(text):
        return ""
    text = str(text).lower()
    text = re.sub(r'http\S+|www\S+', '', text)         # strip embedded links
    text = re.sub(r'[^a-z0-9\s]', ' ', text)             # drop punctuation/symbols
    text = re.sub(r'\s+', ' ', text).strip()             # collapse extra whitespace
    return text


def count_tweets(tweet_ids):
    """tweet_ids column is a space or tab separated string of IDs."""
    if pd.isna(tweet_ids) or str(tweet_ids).strip() == "":
        return 0
    return len(str(tweet_ids).split())


def engineer_features(df):
    df = df.copy()

    # Drop rows with no title at all - can't use them
    df = df[df['title'].notna() & (df['title'].str.strip() != "")]

    df['clean_title'] = df['title'].apply(clean_text)
    df['title_length'] = df['clean_title'].apply(lambda x: len(x.split()))
    df['tweet_count'] = df['tweet_ids'].apply(count_tweets)

    # Simple "sensationalism" signal - exclamation/question marks.
    df['exclaim_count'] = df['title'].apply(lambda t: str(t).count('!'))
    df['question_count'] = df['title'].apply(lambda t: str(t).count('?'))
    df['has_url'] = df['news_url'].notna().astype(int)

    print(f"\nAfter cleaning: {len(df)} rows remain.")
    return df


